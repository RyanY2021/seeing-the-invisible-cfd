@njit(cache=True)
def _blep(t, dt):
    if t < dt:
        t /= dt
        return t + t - t * t - 1.0
    elif t > 1.0 - dt:
        t = (t - 1.0) / dt
        return t * t + t + t + 1.0
    return 0.0


@njit(cache=True)
def osc_saw(freq, ph0):
    n = freq.shape[0]
    out = np.empty(n)
    ph = ph0
    for i in range(n):
        dt = freq[i] / SR
        ph += dt
        if ph >= 1.0:
            ph -= np.floor(ph)
        out[i] = 2.0 * ph - 1.0 - _blep(ph, dt)
    return out


@njit(cache=True)
def osc_pulse(freq, duty, ph0):
    n = freq.shape[0]
    out = np.empty(n)
    ph = ph0
    for i in range(n):
        dt = freq[i] / SR
        ph += dt
        if ph >= 1.0:
            ph -= np.floor(ph)
        y = 1.0 if ph < duty else -1.0
        y += _blep(ph, dt)
        p2 = ph - duty
        if p2 < 0.0:
            p2 += 1.0
        y -= _blep(p2, dt)
        out[i] = y - (2.0 * duty - 1.0)
    return out


@njit(cache=True)
def svf(x, fc, q, mode):
    """Zavalishin TPT state-variable filter. mode 0=LP, 1=BP (unity peak), 2=HP."""
    n = x.shape[0]
    y = np.empty(n)
    ic1 = 0.0
    ic2 = 0.0
    for i in range(n):
        f = fc[i]
        if f < 10.0:
            f = 10.0
        if f > 0.45 * SR:
            f = 0.45 * SR
        g = np.tan(np.pi * f / SR)
        k = 1.0 / q[i]
        a1 = 1.0 / (1.0 + g * (g + k))
        a2 = g * a1
        a3 = g * a2
        v3 = x[i] - ic2
        v1 = a1 * ic1 + a2 * v3
        v2 = ic2 + a2 * ic1 + a3 * v3
        ic1 = 2.0 * v1 - ic1
        ic2 = 2.0 * v2 - ic2
        if mode == 0:
            y[i] = v2
        elif mode == 1:
            y[i] = k * v1
        else:
            y[i] = x[i] - k * v1 - v2
    return y


@njit(cache=True)
def comp_gain(l, r, thr, ratio, up_thr, up_ratio, max_up, att, rel, floor_db):
    """Stereo-linked down/up compressor gain curve (the heart of the OTT emulation)."""
    n = l.shape[0]
    g = np.empty(n)
    env = 0.0
    aa = np.exp(-1.0 / (att * SR))
    ar = np.exp(-1.0 / (rel * SR))
    for i in range(n):
        lv = max(abs(l[i]), abs(r[i]))
        if lv > env:
            env = aa * env + (1.0 - aa) * lv
        else:
            env = ar * env + (1.0 - ar) * lv
        db = 20.0 * np.log10(env + 1e-12)
        gd = 0.0
        if db > thr:
            gd = (thr + (db - thr) / ratio) - db
        elif db < up_thr:
            gd = (up_thr - db) * (1.0 - 1.0 / up_ratio)
            if gd > max_up:
                gd = max_up
            fade = (db - floor_db) / 12.0
            if fade < 0.0:
                fade = 0.0
            if fade > 1.0:
                fade = 1.0
            gd *= fade
        g[i] = 10.0 ** (gd / 20.0)
    return g


@njit(cache=True)
def release_smooth(gm, rel):
    ar = np.exp(-1.0 / (rel * SR))
    g = np.empty_like(gm)
    cur = 1.0
    for i in range(gm.shape[0]):
        tgt = gm[i]
        if tgt < cur:
            cur = tgt
        else:
            cur = tgt + (cur - tgt) * ar
        g[i] = cur
    return g


def arr(v, n):
    return np.full(n, float(v)) if np.isscalar(v) else np.asarray(v, dtype=np.float64)


def filt(x, fc, q=0.707, mode=0):
    n = x.shape[0]
    return svf(np.ascontiguousarray(x, dtype=np.float64), arr(fc, n), arr(q, n), mode)


def sos(kind, f, order=2):
    return signal.butter(order, f, btype=kind, fs=SR, output="sos")


def ramp_env(dur, rel, att=0.003, dec=None, sus=1.0, curve=2.0):
    n_on = max(2, int(round(dur * SR)))
    n_rel = max(2, int(round(rel * SR)))
    e = np.ones(n_on + n_rel)
    na = min(n_on, max(1, int(att * SR)))
    e[:na] = np.linspace(0.0, 1.0, na)
    if dec is not None and n_on > na:
        tt = np.arange(n_on - na) / SR
        e[na:n_on] = sus + (1.0 - sus) * np.exp(-tt / dec)
    e[n_on:] = e[n_on - 1] * (1.0 - np.linspace(0.0, 1.0, n_rel)) ** curve
    return e


VOWEL = {"a": (730, 1090, 2440), "o": (570, 840, 2410), "u": (300, 870, 2240),
         "e": (530, 1840, 2480), "i": (270, 2290, 3010)}


def formant_bank(x, v0, v1, m, shift=1.0, qs=(6.0, 8.0, 10.0), gains=(1.0, 0.6, 0.32)):
    y = np.zeros_like(x)
    for k in range(3):
        f = (VOWEL[v0][k] ** (1.0 - m)) * (VOWEL[v1][k] ** m) * shift
        y += gains[k] * filt(x, f, qs[k], 1)
    return y


def pitch_curve(n, dur, bend=0.0, tape=False):
    t = np.arange(n) / SR
    semi = np.zeros(n)
    amp = np.ones(n)
    if bend:
        b0 = dur * 0.3
        x = np.clip((t - b0) / max(dur - b0, 1e-3), 0.0, 1.0)
        semi = bend * x * x
    if tape:
        x = np.clip(t / dur, 0.0, 1.0)
        speed = np.maximum(1.0 - x, 0.012)
        semi = 12.0 * np.log2(speed)
        amp = np.sqrt(speed)
    return semi, amp


