class Mix:
    def __init__(self):
        self.buses = {}

    def bus(self, name):
        if name not in self.buses:
            self.buses[name] = np.zeros((2, N))
        return self.buses[name]

    def add(self, name, sig, t, gain=1.0, pan=0.0, rev=0.0, room=0.0, dly=0.0):
        if sig.ndim == 1:
            a = (pan + 1.0) * np.pi / 4.0
            sig = np.vstack([sig * np.cos(a), sig * np.sin(a)]) * np.sqrt(2.0)
        i0 = int(round(t * SR))
        if i0 < 0:
            sig = sig[:, -i0:]
            i0 = 0
        if i0 >= N:
            return
        n = min(sig.shape[1], N - i0)
        s = sig[:, :n] * gain
        self.bus(name)[:, i0:i0 + n] += s
        for send, amt in (("rev", rev), ("room", room), ("dly", dly)):
            if amt:
                self.bus(send)[:, i0:i0 + n] += s * amt


class MidiLog:
    CHAN = {"Lead": 0, "Pad": 1, "Sub": 2, "Colorbass": 3, "Chip": 4, "Vox": 5,
            "Pluck": 6, "Keys": 7, "Bell": 8, "Drums": 9}

    def __init__(self):
        self.tracks = defaultdict(list)

    def add(self, track, t, dur, notes, vel=0.8):
        for nt in np.atleast_1d(notes):
            self.tracks[track].append((t, dur, int(nt), int(np.clip(vel * 127, 1, 127))))

    def write(self, path):
        ppq = 480
        tps = ppq * BPM / 60.0

        def vlq(v):
            b = [v & 0x7F]
            v >>= 7
            while v:
                b.append((v & 0x7F) | 0x80)
                v >>= 7
            return bytes(reversed(b))

        def chunk(data):
            return b"MTrk" + len(data).to_bytes(4, "big") + data

        tempo = int(60_000_000 / BPM)
        meta = (b"\x00\xff\x03" + vlq(len(NAME)) + NAME.encode()
                + b"\x00\xff\x51\x03" + tempo.to_bytes(3, "big")
                + b"\x00\xff\x58\x04\x04\x02\x18\x08" + b"\x00\xff\x2f\x00")
        chunks = [chunk(meta)]
        for name, evs in self.tracks.items():
            ch = self.CHAN[name]
            ev = []
            for t, d, nt, v in evs:
                on = int(round(t * tps))
                off = max(on + 1, int(round((t + d) * tps)))
                ev.append((on, 1, bytes([0x90 | ch, nt, v])))
                ev.append((off, 0, bytes([0x80 | ch, nt, 0])))
            ev.sort(key=lambda e: (e[0], e[1]))
            data = b"\x00\xff\x03" + vlq(len(name)) + name.encode()
            last = 0
            for tick, _, msg in ev:
                data += vlq(tick - last) + msg
                last = tick
            data += b"\x00\xff\x2f\x00"
            chunks.append(chunk(data))
        hdr = b"MThd" + (6).to_bytes(4, "big") + (1).to_bytes(2, "big") + len(chunks).to_bytes(2, "big") + ppq.to_bytes(2, "big")
        with open(path, "wb") as fh:
            fh.write(hdr + b"".join(chunks))


def duck_env(events, depth, rel, att=0.004):
    g = np.ones(N)
    na, nr = int(att * SR), int(rel * SR)
    x = np.linspace(0, 1, nr)
    rec = 3 * x ** 2 - 2 * x ** 3
    for t, v in events:
        d = depth * v
        shape = np.concatenate([1 - d * np.linspace(0, 1, na), 1 - d * (1 - rec)])
        i0 = int(t * SR) - na
        i1 = min(N, i0 + shape.shape[0])
        if i0 < 0 or i0 >= N:
            continue
        np.minimum(g[i0:i1], shape[: i1 - i0], out=g[i0:i1])
    return g


def make_ir(rt60, length, predelay, lp_hz, seed):
    r = np.random.default_rng(seed)
    n = int(length * SR)
    t = np.arange(n) / SR
    ir = np.zeros((2, n + int(predelay * SR)))
    for ch in range(2):
        nz = r.standard_normal(n)
        lo = signal.sosfilt(sos("lowpass", 1500), nz)
        hi = nz - lo
        x = lo * 10 ** (-3 * t / rt60) + 0.7 * hi * 10 ** (-3 * t / (rt60 * 0.45))
        x = signal.sosfilt(sos("lowpass", lp_hz), x)
        x[:int(0.004 * SR)] *= np.linspace(0, 1, int(0.004 * SR))
        ir[ch, int(predelay * SR):] = x / np.sqrt(np.sum(x ** 2))
    return ir


def convolve(x, ir):
    return np.vstack([signal.oaconvolve(x[c], ir[c])[:N] for c in range(2)])


def pingpong(x, d=0.3, fb=0.45, taps=7):
    mono = 0.5 * (x[0] + x[1])
    wet = np.zeros((2, N))
    for k in range(1, taps + 1):
        sh = int(k * d * SR)
        wet[(k + 1) % 2, sh:] += mono[:N - sh] * fb ** (k - 1)
    wet = signal.sosfilt(sos("lowpass", 4500), wet)
    return signal.sosfilt(sos("highpass", 300), wet)


def lr4(x, f, kind):
    s = sos(kind, f, 2)
    return signal.sosfilt(s, signal.sosfilt(s, x))


def ott(x, amount=0.7):
    low = lr4(x, 220, "lowpass")
    rest = lr4(x, 220, "highpass")
    mid = lr4(rest, 2500, "lowpass")
    high = lr4(rest, 2500, "highpass")
    out = np.zeros_like(x)
    for band, makeup in ((low, 1.0), (mid, 1.1), (high, 0.85)):
        g = comp_gain(band[0], band[1], -24.0, 4.0, -38.0, 3.0, 10.0, 0.002, 0.06, -62.0)
        out += band * g * makeup
    return (1 - amount) * x + amount * out


def limiter(x, ceiling=0.93, look=0.004, rel=0.08):
    la = int(look * SR)
    pk = np.max(np.abs(x), axis=0)
    req = np.minimum(1.0, ceiling / np.maximum(pk, 1e-9))
    gm = minimum_filter1d(req, size=2 * la + 1, mode="nearest")
    g = release_smooth(gm, rel)
    g = uniform_filter1d(g, size=la, mode="nearest")
    return np.clip(x * g, -ceiling, ceiling)


def softclip(x, knee=0.6):
    a = np.abs(x)
    return np.where(a <= knee, x, np.sign(x) * (knee + (1 - knee) * np.tanh((a - knee) / (1 - knee))))


def shelf(x, f0, gain_db, slope=0.7):
    """RBJ high-shelf biquad."""
    A = 10 ** (gain_db / 40)
    w = 2 * np.pi * f0 / SR
    al = np.sin(w) / 2 * np.sqrt((A + 1 / A) * (1 / slope - 1) + 2)
    c = np.cos(w)
    b = [A * ((A + 1) + (A - 1) * c + 2 * np.sqrt(A) * al), -2 * A * ((A - 1) + (A + 1) * c),
         A * ((A + 1) + (A - 1) * c - 2 * np.sqrt(A) * al)]
    a = [(A + 1) - (A - 1) * c + 2 * np.sqrt(A) * al, 2 * ((A - 1) - (A + 1) * c),
         (A + 1) - (A - 1) * c - 2 * np.sqrt(A) * al]
    return signal.lfilter(np.array(b) / a[0], np.array(a) / a[0], x, axis=1)


def lufs(x):
    """ITU-R BS.1770-4 integrated loudness."""
    f0, G, Q = 1681.974450955533, 3.999843853973347, 0.7071752369554196
    K = np.tan(np.pi * f0 / SR)
    Vh = 10 ** (G / 20)
    Vb = Vh ** 0.4996667741545416
    a0 = 1 + K / Q + K * K
    b1 = [(Vh + Vb * K / Q + K * K) / a0, 2 * (K * K - Vh) / a0, (Vh - Vb * K / Q + K * K) / a0]
    a1 = [1, 2 * (K * K - 1) / a0, (1 - K / Q + K * K) / a0]
    f0, Q = 38.13547087602444, 0.5003270373238773
    K = np.tan(np.pi * f0 / SR)
    a0 = 1 + K / Q + K * K
    b2 = [1, -2, 1]
    a2 = [1, 2 * (K * K - 1) / a0, (1 - K / Q + K * K) / a0]
    y = signal.lfilter(b2, a2, signal.lfilter(b1, a1, x, axis=1), axis=1)
    blk, hop = int(0.4 * SR), int(0.1 * SR)
    ms = np.array([np.sum(np.mean(y[:, i:i + blk] ** 2, axis=1)) for i in range(0, y.shape[1] - blk, hop)])
    lk = -0.691 + 10 * np.log10(ms + 1e-20)
    ms = ms[lk > -70]
    lk = lk[lk > -70]
    rel = -0.691 + 10 * np.log10(np.mean(ms)) - 10
    return -0.691 + 10 * np.log10(np.mean(ms[lk > rel]))


