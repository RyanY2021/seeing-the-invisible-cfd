def kick(vel=1.0):
    n = int(0.55 * SR)
    t = np.arange(n) / SR
    f = 43.65 + 150.0 * np.exp(-t / 0.03) + 420.0 * np.exp(-t / 0.0035)
    body = np.sin(2 * np.pi * np.cumsum(f) / SR)
    amp = np.exp(-t / 0.3)
    amp[-int(0.06 * SR):] *= np.linspace(1, 0, int(0.06 * SR))
    body = np.tanh(2.2 * body * amp) / np.tanh(2.2)
    click = signal.sosfilt(sos("highpass", 2500), rng.standard_normal(n)) * np.exp(-t / 0.0025) * 0.45
    return (body + click) * vel


def snare(vel=1.0, pitch=0.0):
    n = int(0.7 * SR)
    t = np.arange(n) / SR
    p = 2.0 ** (pitch / 12.0)
    body = np.sin(2 * np.pi * np.cumsum(p * (182.0 + 95.0 * np.exp(-t / 0.015))) / SR) * np.exp(-t / 0.085)
    body2 = 0.35 * np.sin(2 * np.pi * 330.0 * p * t) * np.exp(-t / 0.04)
    nz = rng.standard_normal(n)
    noise = signal.sosfilt(sos("bandpass", [min(1300 * p, 6000), 7500]), nz) * np.exp(-t / 0.16)
    snap = signal.sosfilt(sos("highpass", 6000), nz) * np.exp(-t / 0.014)
    cenv = np.zeros(n)
    for d in (0.0, 0.009, 0.019, 0.029):
        cenv += (t >= d) * np.exp(-np.maximum(t - d, 0) / 0.005)
    cenv += 0.55 * np.exp(-t / 0.11)
    clap = signal.sosfilt(sos("bandpass", [900, 3200]), rng.standard_normal(n)) * cenv
    y = 0.95 * body + body2 + 0.75 * noise + 0.22 * snap + 0.55 * clap
    y = np.tanh(1.6 * y)
    y[-int(0.05 * SR):] *= np.linspace(1, 0, int(0.05 * SR))
    return y * vel


HAT_F = (205.3, 304.4, 369.6, 522.7, 540.0, 800.0)


def hat(vel=1.0, open_=False):
    L = 0.45 if open_ else 0.09
    n = int(L * SR)
    t = np.arange(n) / SR
    metal = sum(np.sign(np.sin(2 * np.pi * f * 1.37 * t + rng.random() * 6)) for f in HAT_F)
    metal = signal.sosfilt(sos("bandpass", [7000, 12000]), metal)
    nz = signal.sosfilt(sos("bandpass", [7000, 13000]), rng.standard_normal(n))
    env = np.exp(-t / (0.13 if open_ else 0.017))
    y = (0.5 * metal / 3.0 + 0.6 * nz) * env
    y[-64:] *= np.linspace(1, 0, 64)
    return y * vel


def shaker(vel=1.0):
    n = int(0.08 * SR)
    t = np.arange(n) / SR
    env = np.minimum(t / 0.006, 1.0) * np.exp(-t / 0.025)
    return signal.sosfilt(sos("highpass", 6500), rng.standard_normal(n)) * env * vel


def snap(vel=1.0):
    n = int(0.3 * SR)
    t = np.arange(n) / SR
    cenv = np.zeros(n)
    for d in (0.0, 0.006, 0.013):
        cenv += (t >= d) * np.exp(-np.maximum(t - d, 0) / 0.004)
    cenv += 0.4 * np.exp(-t / 0.05)
    return signal.sosfilt(sos("bandpass", [1600, 6000]), rng.standard_normal(n)) * cenv * vel


def crash(L=2.8, vel=1.0):
    n = int(L * SR)
    t = np.arange(n) / SR
    out = np.zeros((2, n))
    for ch in range(2):
        nz = rng.standard_normal(n)
        metal = sum(np.sin(2 * np.pi * f * (1 + 0.01 * ch) * t + rng.random() * 6)
                    for f in (3150, 4720, 5980, 7340, 8510, 9930))
        s = signal.sosfilt(sos("highpass", 3500), 0.8 * nz + 0.25 * metal)
        out[ch] = s * (0.75 * np.exp(-t / 0.9) + 0.6 * np.exp(-t / 0.05))
    out[:, -int(0.1 * SR):] *= np.linspace(1, 0, int(0.1 * SR))
    return out * vel


def revcrash(L=1.6, vel=1.0):
    c = crash(L + 0.05, vel)[:, ::-1][:, -int(L * SR):].copy()
    c[:, :256] *= np.linspace(0, 1, 256)
    x = np.linspace(0, 1, c.shape[1])
    return c * x ** 1.5


def impact(vel=1.0):
    n = int(3.0 * SR)
    t = np.arange(n) / SR
    f = 30.0 + 65.0 * np.exp(-t / 0.14)
    boom = np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t / 0.9)
    nz = signal.sosfilt(sos("lowpass", 900), rng.standard_normal(n)) * np.exp(-t / 0.25) * 0.6
    y = np.tanh(1.5 * (boom + nz))
    y[-int(0.1 * SR):] *= np.linspace(1, 0, int(0.1 * SR))
    return y * vel


def riser(L, f0=220.0, f1=11000.0, vel=1.0):
    n = int(L * SR)
    t = np.arange(n) / SR
    x = t / L
    fc = f0 * (f1 / f0) ** (x ** 1.5)
    out = np.zeros((2, n))
    for ch in range(2):
        out[ch] = filt(rng.standard_normal(n), fc, 3.0, 1)
    semi = 55.0 + 24.0 * x ** 2
    s = osc_saw(mtof(semi), 0.0) + osc_saw(mtof(semi + 0.18), 0.5)
    s = filt(s, fc * 0.7, 0.9, 0)
    out += 0.22 * s
    out *= (x ** 2.2 + 0.01)
    out[:, -128:] *= np.linspace(1, 0, 128)
    return out * vel


def downlifter(L, vel=1.0):
    n = int(L * SR)
    t = np.arange(n) / SR
    x = t / L
    fc = 9000.0 * (150.0 / 9000.0) ** x
    out = np.zeros((2, n))
    for ch in range(2):
        out[ch] = filt(rng.standard_normal(n), fc, 1.4, 0)
    out *= (1 - x) ** 1.6
    out[:, :128] *= np.linspace(0, 1, 128)
    return out * vel


def vinyl(L):
    n = int(L * SR)
    hiss = signal.sosfilt(sos("bandpass", [900, 7000]), rng.standard_normal((2, n))) * 0.012
    imp = np.zeros((2, n))
    k = int(L * 22)
    pos = rng.integers(0, n, size=(2, k))
    for ch in range(2):
        imp[ch, pos[ch]] = (rng.random(k) ** 4) * rng.choice([-1, 1], k) * 0.9
    crack = signal.sosfilt(sos("highpass", 1800), imp)
    out = hiss + crack
    fade = int(0.8 * SR)
    out[:, :fade] *= np.linspace(0, 1, fade)
    out[:, -fade:] *= np.linspace(1, 0, fade)
    return out


def sub_note(note, dur, bend=0.0, tape=False):
    env = ramp_env(dur, 0.03, att=0.004)
    n = env.shape[0]
    semi, amp = pitch_curve(n, dur, bend, tape)
    ph = 2 * np.pi * np.cumsum(mtof(note + semi)) / SR
    y = np.sin(ph) + 0.2 * np.sin(2 * ph)
    y = np.tanh(1.4 * y) / np.tanh(1.4)
    return y * env * amp


def supersaw(notes, dur, voices=7, spread=0.2, att=0.01, rel=0.3, cutoff=6000.0, q=0.75,
             hp=0.0, dec=None, sus=1.0, width=0.9):
    env = ramp_env(dur, rel, att, dec, sus)
    n = env.shape[0]
    L = np.zeros(n)
    R = np.zeros(n)
    for nt in notes:
        for v in range(voices):
            x = (2.0 * v / (voices - 1) - 1.0) if voices > 1 else 0.0
            f = np.full(n, float(mtof(nt + spread * x + rng.normal(0, 0.01))))
            s = osc_saw(f, rng.random())
            a = (x * width + 1.0) * np.pi / 4.0
            L += s * np.cos(a)
            R += s * np.sin(a)
    L = filt(L, cutoff, q, 0)
    R = filt(R, cutoff, q, 0)
    if hp > 0:
        L = filt(L, hp, 0.7, 2)
        R = filt(R, hp, 0.7, 2)
    return np.vstack([L, R]) * env * (np.sqrt(2.0) / np.sqrt(len(notes) * voices))


def pluck(note, bright=1.0, L=0.45):
    n = int(L * SR)
    t = np.arange(n) / SR
    f = float(mtof(note))
    s = (osc_saw(np.full(n, f * 1.004), rng.random()) + osc_saw(np.full(n, f * 0.996), rng.random())
         + 0.6 * osc_pulse(np.full(n, 2 * f), 0.5, rng.random()))
    y = filt(s, 300.0 + 6500.0 * bright * np.exp(-t / 0.045), 1.8, 0)
    env = np.exp(-t / 0.16)
    env[:88] *= np.linspace(0, 1, 88)
    env[-440:] *= np.linspace(1, 0, 440)
    return y * env * 0.35


def chip(note, dur, duty=0.25, vib=0.25, prev=None, dec=0.35, sus=0.6):
    env = ramp_env(dur, 0.03, 0.002, dec, sus)
    n = env.shape[0]
    t = np.arange(n) / SR
    semi = np.full(n, float(note))
    if prev is not None and abs(prev - note) <= 12:
        semi += (prev - note) * np.exp(-t / 0.012)
    semi += vib * np.clip((t - 0.15) / 0.1, 0, 1) * np.sin(2 * np.pi * 6.2 * t)
    y = osc_pulse(mtof(semi), duty, 0.0)
    return filt(y, 8000.0, 0.7, 0) * env


def vox(note, dur, v0="a", v1="e", scoop=-1.5, breath=0.05):
    env = ramp_env(dur, 0.08, att=0.012)
    n = env.shape[0]
    t = np.arange(n) / SR
    semi = (note + scoop * np.exp(-t / 0.035)
            + 0.13 * np.clip((t - 0.15) / 0.15, 0, 1) * np.sin(2 * np.pi * 5.3 * t))
    src = osc_saw(mtof(semi), 0.0)
    src = filt(src, 3800.0, 0.7, 0)
    src += breath * filt(rng.standard_normal(n), 5000.0, 0.7, 2)
    m = np.clip(t / max(dur, 1e-3), 0, 1) ** 0.8
    y = formant_bank(src, v0, v1, m, shift=1.18, qs=(8.0, 10.0, 12.0), gains=(1.0, 0.7, 0.4))
    return y * env


def epiano(notes, dur, vel=1.0):
    n = int((dur + 0.6) * SR)
    t = np.arange(n) / SR
    y = np.zeros(n)
    for nt in notes:
        f = float(mtof(nt))
        I = 1.5 * np.exp(-t / 0.3) + 0.3
        y += np.sin(2 * np.pi * f * t + I * np.sin(2 * np.pi * f * t)) * np.exp(-t / 2.0)
        y += 0.05 * np.sin(2 * np.pi * 14 * f * t) * np.exp(-t / 0.02)
    g = np.ones(n)
    n_on = int(dur * SR)
    g[n_on:] = np.exp(-np.arange(n - n_on) / SR / 0.15)
    g[:66] *= np.linspace(0, 1, 66)
    g[-441:] *= np.linspace(1, 0, 441)
    y *= g * vel / np.sqrt(len(notes))
    trem = 0.18 * np.sin(2 * np.pi * 3.5 * t)
    return np.vstack([y * (1 + trem), y * (1 - trem)])


def bell(note, dur, vel=1.0):
    n = int((dur + 1.6) * SR)
    t = np.arange(n) / SR
    f = float(mtof(note))
    I = 2.6 * np.exp(-t / 0.35) + 0.25
    y = np.sin(2 * np.pi * f * t + I * np.sin(2 * np.pi * 3.5 * f * t)) * np.exp(-t / 1.0)
    y += 0.4 * np.sin(2 * np.pi * f * t) * np.exp(-t / 1.8)
    y += 0.12 * np.sin(2 * np.pi * 2 * f * t) * np.exp(-t / 0.5)
    g = np.ones(n)
    n_on = int(dur * SR)
    g[n_on:] = np.exp(-np.arange(n - n_on) / SR / 0.35)
    g[:88] *= np.linspace(0, 1, 88)
    g[-441:] *= np.linspace(1, 0, 441)
    return y * g * vel * 0.5


# ----------------------------------------------------------------- the colorbass itself
CH = {
    "Db":  dict(root=1,  sub=37, pcs=[1, 5, 8, 0, 3],  pad=[49, 56, 60, 63, 65]),   # Dbmaj9
    "Eb":  dict(root=3,  sub=39, pcs=[3, 7, 10, 5],    pad=[51, 55, 58, 63, 65]),   # Eb(add9)
    "Cm":  dict(root=0,  sub=36, pcs=[0, 3, 7, 10],    pad=[48, 55, 58, 63, 67]),   # Cm7
    "C7":  dict(root=0,  sub=36, pcs=[0, 4, 7, 10],    pad=[48, 55, 58, 64, 67]),   # C7 -> pulls to Fm
    "Fm":  dict(root=5,  sub=29, pcs=[5, 8, 0, 3, 7],  pad=[53, 56, 60, 63, 67]),   # Fm9
    "Ab":  dict(root=8,  sub=32, pcs=[8, 0, 3, 10],    pad=[44, 51, 58, 60, 63]),   # Ab(add9)
}


def harmonize(top, chord, n_below=2):
    """Stack chord tones under a melody note -> the 'colour' in colorbass."""
    pcs = set(CH[chord]["pcs"])
    out = [top]
    m = top - 3
    while len(out) < n_below + 1 and m > top - 14:
        if m % 12 in pcs and all(abs(m - x) >= 3 for x in out):
            out.append(m)
        m -= 1
    return sorted(out)


def cb_stab(chord, top, dur, vel=1.0, vf="a", vt="o", wob=0.0, bend=0.0, tape=False, bright=1.0):
    """One colorbass hit: FM/saw growl (root-5th-octave) through a vowel formant bank,
    layered with a bright saw chord voiced under the melody note. Same pitch bend on both."""
    env = ramp_env(dur, 0.02 if tape else 0.035, att=0.0025)
    n = env.shape[0]
    t = np.arange(n) / SR
    semi, tape_amp = pitch_curve(n, dur, bend, tape)
    if wob > 0:
        m = 0.5 - 0.5 * np.cos(2 * np.pi * wob * t)
    else:
        m = np.clip(t / max(dur, 1e-3), 0, 1) ** 0.7
    upper = harmonize(top, chord)
    gr = 36 + CH[chord]["root"]
    growl = [gr, gr + 7, gr + 12]
    out = np.zeros((2, n))
    for ch in range(2):
        sg = 1.0 if ch == 0 else -1.0
        acc = np.zeros(n)
        for j, nt in enumerate(growl):
            f = mtof(nt + semi)
            ph = np.cumsum(f) / SR + rng.random()
            idx = 1.0 + 2.6 * m
            fm = np.sin(2 * np.pi * ph + idx * np.sin(2 * np.pi * ph))
            sw = osc_saw(f * 2 ** (sg * 0.08 / 12), rng.random())
            acc += np.tanh(2.8 * (0.65 * fm + 0.5 * sw)) * (1.0 if j == 0 else 0.75)
        fc = 350.0 + 3200.0 * bright * (0.2 + 0.8 * m) + 5000.0 * bright * np.exp(-t / 0.025)
        lp = filt(acc, fc, 2.5, 0)
        fo = formant_bank(acc, vf, vt, m, shift=1.12)
        growl_sig = np.tanh(1.4 * (0.45 * lp + 1.3 * fo))

        acc2 = np.zeros(n)
        for nt in upper:
            f = mtof(nt + semi)
            s = osc_saw(f * 2 ** (sg * 0.11 / 12), rng.random()) + osc_saw(f * 2 ** (-sg * 0.04 / 12), rng.random())
            acc2 += s * (1.25 if nt == top else 0.8)
        fc2 = 700.0 + 6500.0 * bright * np.exp(-t / (0.06 + 0.3 * dur))
        if wob > 0:
            fc2 = fc2 * (0.6 + 0.6 * m)
        chord_sig = np.tanh(0.9 * filt(acc2, fc2, 1.3, 0))
        out[ch] = 0.6 * growl_sig + 0.5 * chord_sig
    return out * env * tape_amp * vel, [*growl, *upper]


