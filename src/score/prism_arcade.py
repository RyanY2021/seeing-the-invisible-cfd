CAL = {   # bus: (bars window, target RMS dBFS) - relative balance auto-set by measurement
    "kick": ((16, 24), -15.0), "snare": ((16, 24), -17.5), "hats": ((16, 24), -31.0),
    "sub": ((16, 24), -15.5), "cb": ((16, 24), -14.0), "pad": ((16, 24), -25.0),
    "chip": ((24, 32), -26.0), "vox": ((52, 56), -22.0), "lead": ((8, 15), -21.5),
    "pluck": ((32, 40), -29.0), "keys": ((32, 40), -27.5), "bell": ((32, 40), -25.0),
    "perc": ((36, 40), -31.0), "vinyl": ((0, 8), -40.0),
    "rev": ((32, 40), -27.5), "room": ((16, 24), -25.0), "dly": ((32, 40), -30.0),
}


FX_GAIN_DB = -10.5   # risers/crashes/impacts sit at a fixed level relative to their design


def rms_db(x, b0, b1):
    seg = x[:, int(T(b0) * SR):int(T(b1) * SR)]
    return 10 * np.log10(np.mean(seg ** 2) + 1e-20)


def mixdown(mix, kicks, snares):
    B = mix.buses
    # sidechain pump (kick) + a little snare ducking on the colorbass
    for name, depth, rel in (("pad", 0.7, 0.2), ("cb", 0.55, 0.16), ("sub", 1.0, 0.11), ("lead", 0.35, 0.18),
                             ("chip", 0.3, 0.15), ("vox", 0.3, 0.15), ("pluck", 0.4, 0.18), ("keys", 0.35, 0.2),
                             ("bell", 0.2, 0.18)):
        if name in B:
            B[name] *= duck_env(kicks, depth, rel)
    B["cb"] *= duck_env(snares, 0.3, 0.1)

    # colorbass bus: high-pass (sub owns the low end) + OTT
    B["cb"] = signal.sosfilt(sos("highpass", 90, 2), B["cb"])
    B["cb"] = ott(B["cb"], 0.75)
    B["sub"] = signal.sosfilt(sos("lowpass", 160, 2), 0.5 * (B["sub"][0] + B["sub"][1]))[None, :].repeat(2, 0)
    B["vox"] = signal.sosfilt(sos("highpass", 250, 2), B["vox"])
    B["chip"] = signal.sosfilt(sos("highpass", 300, 2), B["chip"])

    # returns
    print("  reverb...")
    hall = make_ir(2.6, 3.2, 0.025, 7000, 1)
    room = make_ir(0.7, 1.0, 0.008, 9000, 2)
    B["rev"] = signal.sosfilt(sos("highpass", 220), convolve(B["rev"], hall))
    B["room"] = signal.sosfilt(sos("highpass", 180), convolve(B["room"], room))
    B["dly"] = pingpong(B["dly"])
    pump = duck_env(kicks, 0.35, 0.22)
    B["rev"] *= pump
    B["dly"] *= pump

    report = {}
    for name, ((b0, b1), target) in CAL.items():
        if name not in B:
            continue
        cur = rms_db(B[name], b0, b1)
        B[name] *= 10 ** ((target - cur) / 20)
        report[name] = cur
    B["fx"] *= 10 ** (FX_GAIN_DB / 20)
    mixdown.buses = B
    master = sum(B.values())
    master = signal.sosfilt(sos("highpass", 28, 2), master)
    master = shelf(master, 7500.0, -2.5)

    # gain-stage so the glue comp only kisses the drop peaks (~1 dB) instead of flattening sections
    stage = 10 ** ((-17.0 - rms_db(master, 16, 24)) / 20)
    master *= stage
    # glue compression, soft clip, limiter; iterate the drive to hit the loudness target
    g = comp_gain(master[0], master[1], -14.0, 2.0, -200.0, 1.0, 0.0, 0.01, 0.15, -200.0)
    master *= g
    target, drive = -9.5, 1.0
    for _ in range(4):
        y = limiter(softclip(master * drive))
        L = lufs(y)
        drive *= 10 ** ((target - L) / 20)
    y = limiter(softclip(master * drive))
    fade = int(1.5 * SR)
    y[:, -fade:] *= np.linspace(1, 0, fade) ** 2
    mixdown.stage, mixdown.drive = stage, drive
    return y, report, drive


STEMS = {"Drums": ("kick", "snare", "hats", "perc", "room"), "Bass": ("sub", "cb"),
         "Music": ("pad", "lead", "chip", "pluck", "keys", "bell"), "Vox": ("vox",),
         "FX": ("fx", "vinyl"), "Returns": ("rev", "dly")}


def write_stems():
    d = os.path.join(OUT, "stems")
    os.makedirs(d, exist_ok=True)
    B = mixdown.buses
    for stem, names in STEMS.items():
        x = sum(B[n] for n in names if n in B)
        x = shelf(signal.sosfilt(sos("highpass", 28, 2), x), 7500.0, -2.5) * mixdown.stage * mixdown.drive
        sf.write(os.path.join(d, f"{NAME}_{stem}.wav"), x.T.astype(np.float32), SR, subtype="FLOAT")


def overview_png(y, path, sections=None, title="PRISM ARCADE  -  150 BPM colorbass  -  Ab major", color="#ff6ad5"):
    sections = SECTIONS if sections is None else sections
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    mono = y.mean(axis=0)
    f, t, S = signal.spectrogram(mono, SR, nperseg=4096, noverlap=3072)
    fig, (a1, a2) = plt.subplots(2, 1, figsize=(16, 8), gridspec_kw={"height_ratios": [1, 3]}, sharex=True)
    fig.patch.set_facecolor("#0d0b14")
    hop = int(0.05 * SR)
    env = np.array([np.sqrt(np.mean(mono[i:i + hop] ** 2)) for i in range(0, len(mono) - hop, hop)])
    tt = np.arange(len(env)) * 0.05
    a1.fill_between(tt, -env, env, color=color, lw=0)
    a1.set_facecolor("#0d0b14")
    a1.set_yticks([])
    a2.pcolormesh(t, f, 10 * np.log10(S + 1e-12), shading="auto", cmap="magma", vmin=-110, vmax=-30)
    a2.set_facecolor("black")
    a2.set_yscale("log")
    a2.set_ylim(30, 18000)
    a2.set_xlim(0, len(mono) / SR)
    a2.set_ylabel("Hz", color="w")
    a2.set_xlabel("seconds", color="w")
    for ax in (a1, a2):
        ax.tick_params(colors="w")
        for b, label in sections:
            ax.axvline(T(b), color="#7af7ff", lw=0.8, alpha=0.7)
    for i, (b, label) in enumerate(sections):
        a1.text(T(b) + 0.4, env.max() * (0.85 if i % 2 == 0 else 0.62), label, color="#7af7ff", fontsize=10)
    a1.set_title(title, color="w", fontsize=13)
    plt.tight_layout()
    plt.savefig(path, dpi=110, facecolor=fig.get_facecolor())
    plt.close(fig)


