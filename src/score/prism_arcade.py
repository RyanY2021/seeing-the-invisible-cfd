def parts(bar, steps=16):
    c = SEQ[bar]
    if isinstance(c, str):
        return [(c, 0, steps)]
    return [(c[0], 0, min(8, steps)), (c[1], 8, steps - 8)] if steps > 8 else [(c[0], 0, steps)]


def chord_at(bar, step):
    c = SEQ[bar]
    return c if isinstance(c, str) else (c[0] if step < 8 else c[1])


