def compose():
    mix = Mix()
    midi = MidiLog()
    kicks, snares = [], []

    # ---------------------------------------------------------------- drum helpers
    def KICK(b, s, v=1.0):
        t = T(b, s)
        mix.add("kick", kick(v), t)
        kicks.append((t, v))
        midi.add("Drums", t, STEP, 36, v)

    def SNARE(b, s, v=1.0, pitch=0.0, rev=0.12, room=0.35):
        t = T(b, s)
        mix.add("snare", snare(v, pitch), t, rev=rev, room=room)
        snares.append((t, v))
        midi.add("Drums", t, STEP, 38, v)

    def HAT(b, s, v=0.6, open_=False, pan=0.0):
        t = T(b, s)
        mix.add("hats", hat(v, open_), t, pan=pan, room=0.1)
        midi.add("Drums", t, STEP, 46 if open_ else 42, v)

    def CRASH(b, v=1.0):
        mix.add("fx", crash(2.8, v), T(b), rev=0.2)
        midi.add("Drums", T(b), 1.0, 49, v)

    def snare_roll(b0, cut=8):
        hits = []
        for i, div in enumerate((4, 8, 16, 32)):
            k = 0
            while k * 16 / div < 16:
                s = k * 16 / div
                if i == 3 and s >= cut:
                    break
                hits.append((b0 + i, s))
                k += 1
        for j, (b, s) in enumerate(hits):
            x = j / (len(hits) - 1)
            seg = b - b0                      # 0: 1/4s, 1: 1/8s, 2: 1/16s, 3: 1/32s
            v = (0.4, 0.34, 0.26, 0.2)[seg] * (1.0 + 0.45 * x)
            SNARE(b, s, v, pitch=7 * x ** 2, rev=0.15, room=0.18)

    def drop_drums(b, pos, hats16=False, fill=False):
        KICK(b, 0, 1.0)
        KICK(b, {0: 3, 1: 10, 2: 3, 3: 6}[pos], 0.85)
        SNARE(b, 8)
        if fill:
            for s, v in ((12, 0.45), (13, 0.5), (14, 0.62), (15, 0.78)):
                SNARE(b, s, v, pitch=2)
        elif pos == 3:
            SNARE(b, 15, 0.4)
        for s in range(0, 16, 2):
            HAT(b, s, 0.9 if s % 4 == 2 else 0.5, open_=(s == 14 and pos == 1), pan=0.15)
            if hats16:
                HAT(b, s + 1, 0.28 + 0.1 * rng.random(), pan=-0.2)

    # ---------------------------------------------------------------- melodic helpers
    def PAD(b, gain=1.0, cutoff=5000.0, hp=0.0, steps=16, att=0.08, rel=0.5):
        for name, s0, ln in parts(b, steps):
            sig = supersaw(CH[name]["pad"], ln * STEP, att=att, rel=rel, cutoff=cutoff, hp=hp)
            mix.add("pad", sig, T(b, s0), gain=gain, rev=0.3)
            midi.add("Pad", T(b, s0), ln * STEP, CH[name]["pad"], 0.7 * gain)

    def SUB(b, gain=1.0, steps=16):
        for name, s0, ln in parts(b, steps):
            mix.add("sub", sub_note(CH[name]["sub"], ln * STEP), T(b, s0), gain=gain)
            midi.add("Sub", T(b, s0), ln * STEP, CH[name]["sub"], gain)

    ARP = [0, 2, 1, 3, 2, 4, 3, 1, 0, 2, 1, 3, 2, 4, 3, 4]

    def ARPS(b, bright, gain=1.0):
        for s in range(16):
            name = chord_at(b, s)
            p = CH[name]["pad"]
            tones = sorted(p[1:]) + [p[1] + 12]
            nt = tones[ARP[s]] + 12
            v = gain * (1.0 if s % 4 == 0 else 0.75 if s % 2 == 0 else 0.55)
            mix.add("pluck", pluck(nt, bright), T(b, s), gain=v, pan=0.35 * np.sin(s * 0.9), rev=0.2, dly=0.28)
            midi.add("Pluck", T(b, s), STEP, nt, v)

    def LEAD(events, cutoff_fn, max_step=None):
        for (b, s, d, m) in events:
            if max_step is not None and b == max_step[0] and s >= max_step[1]:
                continue
            notes = [m - 12, m]
            sig = supersaw(notes, d * STEP * 0.92, voices=5, spread=0.16, att=0.004, rel=0.12,
                           cutoff=cutoff_fn(b, s), q=1.0, width=0.8)
            mix.add("lead", sig, T(b, s), rev=0.25, dly=0.15)
            midi.add("Lead", T(b, s), d * STEP, notes, 0.9)

    def CHIP(events, octave=0, gain=1.0, max_step=None):
        prev = None
        for (b, s, d, m) in events:
            if max_step is not None and b == max_step[0] and s >= max_step[1]:
                continue
            nt = m + octave
            mix.add("chip", chip(nt, d * STEP * 0.9, prev=prev), T(b, s), gain=gain, rev=0.12, dly=0.18)
            midi.add("Chip", T(b, s), d * STEP, nt, gain)
            prev = nt

    def BELL(events, gain=1.0, octave=-12):
        for (b, s, d, m) in events:
            nt = m + octave
            mix.add("bell", bell(nt, d * STEP), T(b, s), gain=gain, rev=0.4, dly=0.2, pan=0.1)
            midi.add("Bell", T(b, s), d * STEP, nt, gain)

    def VOX(b, s, nt, dur, v0, v1, gain=1.0, scoop=-1.5, rev=0.3, dly=0.2):
        mix.add("vox", vox(nt, dur, v0, v1, scoop), T(b, s), gain=gain, rev=rev, dly=dly)
        midi.add("Vox", T(b, s), dur, nt, gain)

    def CB(b, s, chord, top, dur, **kw):
        sig, notes = cb_stab(chord, top, dur, **kw)
        mix.add("cb", sig, T(b, s), rev=0.04)
        midi.add("Colorbass", T(b, s), dur, notes, kw.get("vel", 1.0))

    VOW_A = [("a", "o"), ("o", "a"), ("a", "e"), ("e", "o"), ("o", "u"), ("u", "a"), ("i", "a")]
    VOW_B = [("i", "a"), ("a", "o"), ("e", "a"), ("o", "i"), ("u", "e"), ("a", "i")]

    def CB_HOOK(events, vowels, wob, bright=1.0, final_bend=-12):
        for i, (b, s, d, m) in enumerate(events):
            last = i == len(events) - 1
            dur = d * STEP * (0.82 if d <= 2 else 0.9)
            vf, vt = vowels[i % len(vowels)]
            CB(b, s, chord_at(b, s), m - 12, dur, vel=1.0 if s == 0 else 0.86, vf=vf, vt=vt,
               wob=wob if d >= 4 else 0.0, bend=final_bend if last else 0.0, bright=bright)

    # =========================================================== INTRO  (bars 0-7)
    mix.add("vinyl", vinyl(8 * BAR + 1.0), 0.0)
    for b in range(INTRO, BUILD1):
        PAD(b, gain=0.5, cutoff=500 * 7.0 ** ((b - INTRO) / 7), att=1.2 if b == 0 else 0.08)
    for b in range(2, 8):
        ARPS(b, bright=0.15 + 0.08 * (b - 2), gain=0.32 + 0.07 * (b - 2))
    BELL(hook(4), gain=0.4)
    for b in range(4, 8):
        for s in range(2, 16, 4):
            HAT(b, s, 0.35, pan=0.2)
    mix.add("fx", riser(2 * BAR, vel=0.45), T(6))
    mix.add("fx", revcrash(1.6, 0.6), T(8) - 1.6)

    # =========================================================== BUILD 1  (bars 8-15)
    CRASH(8, 0.6)
    for b in range(BUILD1, DROP1):
        k = (b - BUILD1) / 7
        PAD(b, gain=0.55, cutoff=3500 + 3500 * k, hp=0 if b < 12 else 150 + 700 * (b - 12) / 3, steps=8 if b == 15 else 16)
    LEAD(hook(8, "auto") + hook(12, "auto"), lambda b, s: 1800 + 5500 * ((b - 8) * 16 + s) / 128, max_step=(15, 8))
    for b in range(12, 16):
        for s in range(0, 16 if b < 15 else 8, 2):
            name = chord_at(b, s)
            sig = supersaw(CH[name]["pad"], 0.12, voices=5, att=0.002, rel=0.08,
                           cutoff=2000 + 5000 * (b - 12) / 3, hp=200 + 300 * (b - 12))
            mix.add("pad", sig, T(b, s), gain=0.7, rev=0.15)
    for b in range(8, 12):
        KICK(b, 0, 0.75)
        KICK(b, 8, 0.75)
        SNARE(b, 4, 0.45)
        SNARE(b, 12, 0.5)
        for s in range(2, 16, 4):
            HAT(b, s, 0.6, pan=0.15)
    for b in range(12, 16):
        for s in (0, 4, 8, 12) if b < 15 else (0, 4):
            KICK(b, s, 0.7)
    snare_roll(12, cut=8)
    mix.add("fx", riser(4 * BAR, vel=0.55), T(12))
    mix.add("fx", revcrash(1.6, 0.9), T(16) - 1.6)
    VOX(15, 8, 75, 0.55, "a", "e", gain=1.0, scoop=-3, rev=0.45, dly=0.4)

    # =========================================================== DROP 1  (bars 16-31)
    mix.add("fx", impact(), T(16))
    CRASH(16)
    CRASH(24, 0.8)
    for p in (16, 20, 24, 28):
        CB_HOOK(hook(p, "auto"), VOW_A, wob=5.0, final_bend=-24 if p == 28 else -12)
    CHIP(hook(24, "auto") + hook(28, "auto"), gain=0.9)
    for (b, s, d, m) in hook(28, "auto"):
        if d >= 3:
            VOX(b, s, m - 12, d * STEP * 0.85, *VOW_A[(b + s) % len(VOW_A)], gain=0.75)
    for b in range(DROP1, BREAK):
        SUB(b)
        PAD(b, gain=0.5, cutoff=4500)
        drop_drums(b, (b - DROP1) % 4, hats16=b >= 24, fill=b == 31)

    # =========================================================== BREAKDOWN  (bars 32-39)
    mix.add("fx", downlifter(2 * BAR, 0.8), T(32))
    CRASH(32, 0.5)
    KEYS_RHY = [(0, 3), (3, 3), (6, 4), (10, 2), (12, 4)]
    for b in range(BREAK, BUILD2):
        k = (b - BREAK) / 7
